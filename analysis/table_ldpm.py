"""LaTeX tables for the latent-diffusion UQ comparison.

Same shape as tables/final/corr_mse.tex so the two can sit side by side in the response: bold
is best, underline second, ranked on the SIGNED correlation (a method that anti-correlates
with error is not "good at large magnitude").

One row per method and one column per test group, pooling the two datasets, exactly as the
VAE table does. There is no "Encoder std." row: that baseline is the VAE encoder's own
predicted sigma, and a diffusion model has no encoder to read it from.

Memory is quoted as a multiple of the parameter count p, computed for THIS model
(27,159,300 params), not carried over from the VAE.

Usage
-----
  python analysis/table_ldpm.py --csv tables/ldpm_fitz_*_t400.csv tables/ldpm_ai4skin_*_t400.csv \\
      --metric mse --out tables/final/ldpm_corr_mse.tex
"""
import argparse
import glob
import os
from collections import defaultdict

import numpy as np
import pandas as pd
from scipy.stats import pearsonr, spearmanr
from sklearn.metrics import roc_auc_score

p = argparse.ArgumentParser()
p.add_argument("--csv", nargs="+", required=True)
p.add_argument("--metric", default="mse", choices=["mse", "ssim", "lpips", "latent_mse"])
p.add_argument("--kind", default="corr", choices=["corr", "auroc"])
p.add_argument("--out", default=None)
p.add_argument("--n_params", type=int, default=27159300)
p.add_argument("--sketch_size", type=int, default=10000)
p.add_argument("--n_vec", type=int, default=90)
p.add_argument("--tail", type=float, default=0.1, help="auroc: worst-tail fraction")
cli = p.parse_args()

# display name, csv column, memory
METHODS = [
    ("MC-dropout",          "dropout",  r"$\sim\!0$"),
    ("Low-rank LLA",        "lla",      "$1p$"),
    ("SWAG",                "swag",     "$3p$"),
    ("Deep ensemble (M=5)", "ensemble", "$5p$"),
    ("SLUG (ours)",         "slug",     None),
]
SLUG_MEM = cli.n_vec * cli.sketch_size / cli.n_params

# SSIM is a similarity: a good uncertainty score should ANTI-correlate with it. Flipping the
# sign here means every column in the table is "higher is better", so one ranking rule works
# for all three metrics.
SIGN = -1.0 if cli.metric == "ssim" else 1.0

# Match the VAE tables' column names and order, so the two can be read side by side.
# The underscores also have to go: they are subscripts in LaTeX maths mode.
RENAME = {"light_skin": "FST12", "dark_skin": "FST56", "HUSC": "HUSC", "HCUV": "HCUV"}
ORDER = ["FST12", "FST56", "HUSC", "HCUV"]

files = [f for pat in cli.csv for f in sorted(glob.glob(pat))]
if not files:
    raise SystemExit("no CSVs matched")

# vals[method][group] = list over seeds/files
vals = defaultdict(lambda: defaultdict(list))
groups = []
for f in files:
    df = pd.read_csv(f)
    for g, sub in df.groupby("group", sort=False):
        g = RENAME.get(g, g)
        if g not in groups:
            groups.append(g)
        for _, col, _ in METHODS:
            if col not in sub.columns or sub[col].isna().all():
                continue
            u, e = sub[col].values, sub[cli.metric].values
            if cli.kind == "corr":
                vals[col][g].append((SIGN * pearsonr(u, e)[0],
                                     SIGN * spearmanr(u, e).correlation))
            else:
                thr = np.quantile(e, 1 - cli.tail) if SIGN > 0 else np.quantile(e, cli.tail)
                y = (e >= thr) if SIGN > 0 else (e <= thr)
                vals[col][g].append((roc_auc_score(y, u),))

groups = [g for g in ORDER if g in groups] + [g for g in groups if g not in ORDER]
print(f"{len(files)} file(s), groups: {groups}")


def cellstr(v, best, second, n):
    """mean +- std over files; std is omitted when a single file defines the method."""
    m = float(np.mean(v))
    s = f"{m:.3f}" if n < 2 else f"{m:.3f}\\,$\\pm$\\,{float(np.std(v)):.3f}"
    if np.isclose(m, best):
        return f"\\textbf{{{s}}}"
    if np.isclose(m, second):
        return f"\\underline{{{s}}}"
    return s


rows, nsub = [], (2 if cli.kind == "corr" else 1)
for gi in range(nsub):
    pass

# rank per group on the primary statistic (Pearson for corr, AUROC otherwise)
rank = {}
for g in groups:
    means = {col: np.mean([t[0] for t in vals[col][g]])
             for _, col, _ in METHODS if vals[col][g]}
    order = sorted(means.values(), reverse=True)
    rank[g] = (order[0] if order else None, order[1] if len(order) > 1 else None)
rank2 = {}
if cli.kind == "corr":
    for g in groups:
        means = {col: np.mean([t[1] for t in vals[col][g]])
                 for _, col, _ in METHODS if vals[col][g]}
        order = sorted(means.values(), reverse=True)
        rank2[g] = (order[0] if order else None, order[1] if len(order) > 1 else None)

L = []
L.append(f"% Auto-generated by analysis/table_ldpm.py --metric {cli.metric} --kind {cli.kind}")
L.append("% Latent diffusion model (27.2M-param UNet on SD-VAE latents), 50/50 training split.")
L.append("% Bold = best, underline = second best, ranked on the SIGNED correlation."
         if cli.kind == "corr" else
         f"% Bold = best, underline = second. AUROC for detecting the worst "
         f"{int(cli.tail*100)}\\% of images by {cli.metric}.")
L.append(r"\begin{center}")
L.append(r"\small")
L.append(r"\begin{tabular}{ll" + "c" * len(groups) + "}")
L.append(r"\toprule")
L.append("Method & Memory & " + " & ".join(groups) + r" \\")
L.append(r"\midrule")

for i, (name, col, mem) in enumerate(METHODS):
    if not any(vals[col][g] for g in groups):
        continue
    if mem is None:
        mem = f"${SLUG_MEM:.3f}p$"
    cells = []
    for g in groups:
        v = [t[0] for t in vals[col][g]]
        cells.append(cellstr(v, *rank[g], len(v)) if v else "--")
    L.append(f"{name} & {mem} & " + " & ".join(cells) + r" \\")
    if cli.kind == "corr":
        cells = []
        for g in groups:
            v = [t[1] for t in vals[col][g]]
            cells.append(cellstr(v, *rank2[g], len(v)) if v else "--")
        L.append(r"\quad\textit{Spearman} & & " + " & ".join(cells) + r" \\")
    if i < len(METHODS) - 1:
        L.append(r"\addlinespace")

L.append(r"\bottomrule")
L.append(r"\end{tabular}")
L.append(r"\end{center}")
tex = "\n".join(L)
print(tex)
if cli.out:
    os.makedirs(os.path.dirname(cli.out), exist_ok=True)
    open(cli.out, "w").write(tex + "\n")
    print(f"\n-> {cli.out}")
